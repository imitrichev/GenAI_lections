import re
#модуль для поиска, проверки и извлечения фрагментов текста по шаблону

class SentimentAnalyzerTool:
    """Инструмент для аналииза тональности текста"""

    name = "sentiment_analyzer"
    description = (
        "Анализирует тональность текста: позитивная, негативная или нейтральная."
        "работает локально, на основе словаря ключевых слов."
    )

    positive_words = {
        "хорошо", "хороший", "хорошая", "хорошее",
        "отлично", "отличный", "отличная", "отличное",
        "прекрасно", "прекрасный", "прекрасная", "прекрасное",
        "замечательно", "замечательный", "замечательная", "замечательное",
        "супер", "класс", "круто", "великолепно", "восторг",
        "радость", "рад", "рада", "драды", "довольный", "довольная", "довольны",
    }
    negative_words = {
        "плохо", "плохой", "плохая", "плохое",
        "ужасное", "ужасный", "ужасная", "ужасно",
        "отвратительно", "отвратительный", "отвратительная", "отвратительное",
        "кошмар", "проблемный", "проблемная", "жаль", "ненавижу",
        "разочарование", "разочарован", "разочарована",
    }

    def use(self, text: str) -> str:
        """
        Анализирует тональность переданного текста.
        """
        if text is None or not str(text).strip():
            return "Ошибка: получен пустой текст"

        words = re.findall(r"[а-яёa-z]+", text.lower())
        positive_count = sum(1 for w in words if w in self.positive_words)
        negative_count = sum(1 for w in words if w in self.negative_words)
        res_count = positive_count - negative_count

        if res_count > 0:
            sentiment = "позитивная"
        elif res_count < 0:
            sentiment = "негативная"
        else:
            sentiment = "нейтральная"

        return (
            f"Тональность текста:     {sentiment}. "
            f"Позитивных слов:     {positive_count}, "
            f"Негативных слов:     {negative_count}."
        )
